function DataTab({ d }: any) {
  return (
    <div className="split">
      <section className="panel panel-pad">
        <h2>Data sources and licences</h2>
        <table className="data">
          <thead>
            <tr>
              <th>Source</th>
              <th>Role</th>
              <th>Licence</th>
            </tr>
          </thead>
          <tbody>
            {SOURCES.map(([a, b, c]) => (
              <tr key={a}>
                <td style={{ fontWeight: 600 }}>{a}</td>
                <td className="small">{b}</td>
                <td className="small">{c}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </section>
      <section className="panel panel-pad stack">
        <h2>Known limitations</h2>
        <ul className="small" style={{ margin: 0, paddingLeft: 18, lineHeight: 1.6 }}>
          <li>Spontaneous reports measure reporting, not incidence. A high EB05 is a reason to review cases, never proof of harm.</li>
          <li>The FAERS extracts are pre aggregated tables for four drug groups, not the full case level database, so signals cannot be stratified by age, sex or time.</li>
          <li>Label derived references are incomplete (SIDER has no entries for atorvastatin or warfarin), so precision against them is a lower bound.</li>
          <li>The literature corpus ends in 2017; newer evidence enters only through the curated guidance digests, which must be checked against current guidance.</li>
          <li>The verifier checks wording, numbers, drugs, reactions and negation. It does not prove that an answer is clinically correct.</li>
          <li>The interaction triage level is a heuristic for ordering review, not a validated severity scale.</li>
          <li>This is a research and portfolio system. It is not a medical device and must not guide individual treatment.</li>
        </ul>
        {d.blind_hash_matches !== undefined && <p className="small">Blind question set unchanged since it was frozen: {d.blind_hash_matches ? "confirmed" : "hash mismatch"}.</p>}
      </section>
    </div>
  );
}
