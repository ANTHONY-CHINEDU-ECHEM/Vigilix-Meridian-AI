import { useState } from "react";
import { ErrorNote, fmt, int, pct, Spinner, Tabs, useAsync, useEngine } from "../components/ui";

const MODE_NAMES: Record<string, string> = {
  bm25: "BM25",
  sif: "SIF word vectors",
  dense: "Dual encoder",
  hybrid: "Hybrid fusion",
  entity: "Fusion with entity routing",
  full: "Full pipeline with reranker",
};

const SOURCES = [
  ["PubMed 200k RCT", "Randomised trial abstracts, filtered to drug safety", "CC BY 4.0"],
  ["ADE corpus (Gurulingappa 2012)", "Case report sentences with drug and adverse effect relations", "Research use"],
  ["DDI corpus 2013", "DrugBank and MEDLINE interaction texts", "CC BY NC 3.0"],
  ["BioCreative V CDR", "Chemical induced disease abstracts", "Research use"],
  ["OnSIDES annotations and Demner Fushman labels", "US, UK and EU label safety sections with annotated adverse events", "CC BY 4.0"],
  ["Hetionet (SIDER 4.1, DrugCentral, DrugBank, PharmacotherapyDB)", "Side effects, classes, indications and targets", "CC0 with CC BY NC SA components"],
  ["FAERS extracts (MDDC package; Kim and Yoon 2023)", "Drug and preferred term report counts, 2014 to 2023", "US public domain"],
  ["OMOP and EU ADR reference sets", "Positive and negative drug outcome controls", "Apache 2.0"],
  ["WHO ATC classification", "Anatomical therapeutic chemical classes", "WHO terms"],
];

export default function Evaluation() {
  const engine = useEngine();
  const { data, error, loading } = useAsync(() => engine.evaluation(), [engine]);
  const [tab, setTab] = useState("retrieval");
  return (
    <div className="page">
      <div className="page-head">
        <div>
          <h1>Evaluation and governance</h1>
          <p>Every number here is regenerated by one command (python scripts/run_evaluation.py) from public data. Limitations are reported next to results rather than hidden.</p>
        </div>
      </div>
      {loading && <Spinner label="Loading reports" />}
      {error && <ErrorNote error={error} />}
      {data && (
        <>
          <Tabs
            value={tab}
            onChange={setTab}
            tabs={[
              { id: "retrieval", label: "Retrieval" },
              { id: "answers", label: "Grounded answers" },
              { id: "signals", label: "Signal detection" },
              { id: "extraction", label: "Extraction" },
              { id: "data", label: "Data and limitations" },
            ]}
          />
          {tab === "retrieval" && <Retrieval d={data} engine={engine} />}
          {tab === "answers" && <Answers d={data} engine={engine} />}
          {tab === "signals" && <SignalsEval d={data} engine={engine} />}
          {tab === "extraction" && <Extraction d={data} engine={engine} />}
          {tab === "data" && <DataTab d={data} />}
        </>
      )}
    </div>
  );
}

function Fig({ engine, name, alt }: { engine: any; name: string; alt: string }) {
  return <img className="figure" src={engine.figureUrl(name)} alt={alt} loading="lazy" />;
}

